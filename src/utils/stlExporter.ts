import * as THREE from 'three';

/**
 * Generates a standard binary STL ArrayBuffer from a Three.js BufferGeometry.
 * In Three.js, Y is vertical (height above the build plate).
 * In 3D Slicers (Cura, PrusaSlicer, Bambu Studio, OrcaSlicer), Z is the vertical build axis.
 * By default, zUp: true converts Three.js (x, y, z) -> Slicer (x, -z, y), ensuring
 * the model lands 100% flat on the build plate with Z = 0 as the bottom face.
 */
export function geometryToBinarySTL(
  geometry: THREE.BufferGeometry,
  options?: { zUp?: boolean }
): ArrayBuffer {
  const zUp = options?.zUp ?? true;

  // Ensure non-indexed geometry or clone to non-indexed
  const g = geometry.index ? geometry.toNonIndexed() : geometry.clone();
  g.computeVertexNormals();

  const posAttr = g.getAttribute('position');
  const normAttr = g.getAttribute('normal');

  const triangleCount = posAttr.count / 3;
  const bufferSize = 84 + triangleCount * 50;
  const buffer = new ArrayBuffer(bufferSize);
  const dataView = new DataView(buffer);

  // 80-byte header
  const header = 'Binary STL generated by Dual3D Studio (Z-Up Slicer Ready)';
  for (let i = 0; i < 80; i++) {
    dataView.setUint8(i, i < header.length ? header.charCodeAt(i) : 0);
  }

  // 4-byte triangle count
  dataView.setUint32(80, triangleCount, true);

  let offset = 84;
  const pA = new THREE.Vector3();
  const pB = new THREE.Vector3();
  const pC = new THREE.Vector3();
  const cb = new THREE.Vector3();
  const ab = new THREE.Vector3();
  const normal = new THREE.Vector3();

  for (let i = 0; i < triangleCount; i++) {
    const idx = i * 3;

    pA.fromBufferAttribute(posAttr, idx);
    pB.fromBufferAttribute(posAttr, idx + 1);
    pC.fromBufferAttribute(posAttr, idx + 2);

    if (normAttr) {
      normal.fromBufferAttribute(normAttr, idx);
    } else {
      cb.subVectors(pC, pB);
      ab.subVectors(pA, pB);
      cb.cross(ab).normalize();
      normal.copy(cb);
    }

    // Convert coordinates: If zUp is true, Three.js Y (height) becomes Slicer Z,
    // and Three.js Z becomes Slicer -Y so the XY footprint rests directly on the bed.
    const nx = normal.x;
    const ny = zUp ? -normal.z : normal.y;
    const nz = zUp ? normal.y : normal.z;

    const ax = pA.x;
    const ay = zUp ? -pA.z : pA.y;
    const az = zUp ? pA.y : pA.z;

    const bx = pB.x;
    const by = zUp ? -pB.z : pB.y;
    const bz = zUp ? pB.y : pB.z;

    const cx = pC.x;
    const cy = zUp ? -pC.z : pC.y;
    const cz = zUp ? pC.y : pC.z;

    // Normal vector
    dataView.setFloat32(offset, nx, true);
    dataView.setFloat32(offset + 4, ny, true);
    dataView.setFloat32(offset + 8, nz, true);
    offset += 12;

    // Vertex 1
    dataView.setFloat32(offset, ax, true);
    dataView.setFloat32(offset + 4, ay, true);
    dataView.setFloat32(offset + 8, az, true);
    offset += 12;

    // Vertex 2
    dataView.setFloat32(offset, bx, true);
    dataView.setFloat32(offset + 4, by, true);
    dataView.setFloat32(offset + 8, bz, true);
    offset += 12;

    // Vertex 3
    dataView.setFloat32(offset, cx, true);
    dataView.setFloat32(offset + 4, cy, true);
    dataView.setFloat32(offset + 8, cz, true);
    offset += 12;

    // 2-byte attribute count
    dataView.setUint16(offset, 0, true);
    offset += 2;
  }

  return buffer;
}

/**
 * Downloads an ArrayBuffer as a binary STL file
 */
export function downloadSTL(
  geometry: THREE.BufferGeometry,
  filename: string = 'model_3d.stl',
  options?: { zUp?: boolean }
) {
  const binarySTL = geometryToBinarySTL(geometry, options);
  const blob = new Blob([binarySTL], { type: 'application/octet-stream' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.stl') ? filename : `${filename}.stl`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Exports geometry to standard OBJ format
 */
export function exportToOBJ(
  geometry: THREE.BufferGeometry,
  filename: string = 'model_3d.obj',
  options?: { zUp?: boolean }
) {
  const zUp = options?.zUp ?? true;
  const g = geometry.index ? geometry.toNonIndexed() : geometry.clone();
  g.computeVertexNormals();

  const posAttr = g.getAttribute('position');
  const normAttr = g.getAttribute('normal');

  let objText = '# Exported from Dual3D Studio (Z-Up Slicer Ready)\n';
  objText += `o ${filename.replace('.obj', '')}\n`;

  for (let i = 0; i < posAttr.count; i++) {
    const x = posAttr.getX(i);
    const y = zUp ? -posAttr.getZ(i) : posAttr.getY(i);
    const z = zUp ? posAttr.getY(i) : posAttr.getZ(i);
    objText += `v ${x.toFixed(4)} ${y.toFixed(4)} ${z.toFixed(4)}\n`;
  }

  if (normAttr) {
    for (let i = 0; i < normAttr.count; i++) {
      const nx = normAttr.getX(i);
      const ny = zUp ? -normAttr.getZ(i) : normAttr.getY(i);
      const nz = zUp ? normAttr.getY(i) : normAttr.getZ(i);
      objText += `vn ${nx.toFixed(4)} ${ny.toFixed(4)} ${nz.toFixed(4)}\n`;
    }
  }

  for (let i = 0; i < posAttr.count; i += 3) {
    const v1 = i + 1;
    const v2 = i + 2;
    const v3 = i + 3;
    if (normAttr) {
      objText += `f ${v1}//${v1} ${v2}//${v2} ${v3}//${v3}\n`;
    } else {
      objText += `f ${v1} ${v2} ${v3}\n`;
    }
  }

  const blob = new Blob([objText], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.obj') ? filename : `${filename}.obj`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Calculates volume, dimensions and print statistics
 */
export function calculateGeometryStats(geometry: THREE.BufferGeometry, targetHeightMm: number = 40) {
  geometry.computeBoundingBox();
  const box = geometry.boundingBox || new THREE.Box3();
  const size = new THREE.Vector3();
  box.getSize(size);

  const triangleCount = geometry.index
    ? geometry.index.count / 3
    : geometry.getAttribute('position')
      ? geometry.getAttribute('position').count / 3
      : 0;

  // Approximate volume via bounding box and density ratio or sum of signed tetrahedron volumes
  const g = geometry.index ? geometry.toNonIndexed() : geometry;
  const pos = g.getAttribute('position');
  let volumeMm3 = 0;

  if (pos) {
    const p1 = new THREE.Vector3();
    const p2 = new THREE.Vector3();
    const p3 = new THREE.Vector3();
    for (let i = 0; i < pos.count; i += 3) {
      p1.fromBufferAttribute(pos, i);
      p2.fromBufferAttribute(pos, i + 1);
      p3.fromBufferAttribute(pos, i + 2);
      // Signed volume of tetrahedron formed with origin
      volumeMm3 += p1.dot(p2.cross(p3)) / 6.0;
    }
  }
  volumeMm3 = Math.abs(volumeMm3);

  // If calculation gives 0 (e.g. open surface), fallback to 35% bounding box
  if (volumeMm3 < 1) {
    volumeMm3 = size.x * size.y * size.z * 0.35;
  }

  const volumeCm3 = volumeMm3 / 1000.0;
  // PLA density approx 1.24 g/cm3, with 20% infill and 2 walls effective density ~ 0.45 of solid
  const estimatedWeightGrams = Math.max(1, Math.round(volumeCm3 * 1.24 * 0.45));

  // Print speed approx 12-18 grams per hour for standard 0.2mm layer height
  const printTimeMinutes = Math.max(10, Math.round((estimatedWeightGrams / 15) * 60));

  const warnings: string[] = [];
  if (size.x > 220 || size.y > 220 || size.z > 220) {
    warnings.push('O modelo excede a mesa padrão de 220x220mm. Reduza a escala ou dimensione no fatiador.');
  }
  if (size.x < 10 || size.y < 10 || size.z < 5) {
    warnings.push('O modelo é muito pequeno (<10mm). Paredes finas podem não imprimir com bico 0.4mm.');
  }

  return {
    dimensions: {
      x: Math.round(size.x * 10) / 10,
      y: Math.round(size.y * 10) / 10,
      z: Math.round(size.z * 10) / 10,
    },
    triangleCount: Math.round(triangleCount),
    estimatedWeightGrams,
    estimatedPrintTimeMinutes: printTimeMinutes,
    isPrintable: warnings.length === 0,
    warnings,
  };
}

/**
 * Downloads multiple STL files (for multi-color printing / separate parts assembly)
 */
export function downloadMultiPartSTLs(
  parts: { name: string; geometry: THREE.BufferGeometry }[],
  basePrefix: string
) {
  parts.forEach((part, idx) => {
    if (part.geometry && part.geometry.getAttribute('position') && part.geometry.getAttribute('position').count > 0) {
      setTimeout(() => {
        downloadSTL(part.geometry, `${basePrefix}_${part.name}.stl`);
      }, idx * 250);
    }
  });
}
